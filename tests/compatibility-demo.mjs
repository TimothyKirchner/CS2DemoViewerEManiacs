import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
import {parseDemo} from "../web/parse-demo.mjs";
import {validateReplay} from "../web/core.mjs";
import {createReport,finishReport} from "../web/diagnostics.mjs";
const vendor=new URL("../web/vendor/",import.meta.url);
vm.runInThisContext(fs.readFileSync(new URL("demoparser2.js",vendor),"utf8")+";globalThis.dp=wasm_bindgen;");
await dp({module_or_path:fs.readFileSync(new URL("demoparser2_bg.wasm",vendor))});
const bytes=new Uint8Array(fs.readFileSync(process.argv[2]));
const report=createReport({name:"regression.dem",size:bytes.length});
const replay=validateReplay(await parseDemo(bytes,"regression.dem",dp,report,m=>console.log(m.stage)));
finishReport(report);
assert.equal(report.status,"completed");assert.equal(report.warnings.length,0);
assert.equal(replay.map,process.argv[3]??replay.map);
assert(replay.rounds.length>1);assert(replay.players.length>=10);
assert(replay.rounds.every(r=>r.frames.length));assert(replay.rounds.some(r=>r.grenades.length));
for(const r of replay.rounds)for(const f of r.frames)for(const p of f.players)assert(Number.isFinite(p.x)&&Number.isFinite(p.y)&&Number.isFinite(p.yaw));
console.log(JSON.stringify({map:replay.map,rounds:replay.rounds.length,players:replay.players.length,pistols:replay.pistols.map(i=>replay.rounds[i].number),paths:replay.rounds.reduce((n,r)=>n+r.grenades.length,0),playerSamples:report.context.playerSampleCount,grenadeSamples:report.context.grenadeSampleCount,warnings:replay.warnings},null,2));
